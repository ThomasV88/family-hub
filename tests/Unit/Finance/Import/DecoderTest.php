<?php

use App\Finance\Import\Decoder;
use App\Finance\Import\ImportError;
use Tests\Support\CsvFixtures;
use Tests\TestCase;

uses(TestCase::class);

function refused(callable $fn): ?string
{
    try {
        $fn();
    } catch (ImportError $e) {
        return $e->code;
    }

    return null;
}

it('keeps committed fixtures equal to generated bytes', function () {
    foreach (CsvFixtures::committed() as $name => $opts) {
        expect(file_get_contents(__DIR__.'/../../../fixtures/finance/'.$name))->toBe(CsvFixtures::statement($opts), $name);
    }
});

it('has the finance config', function () {
    expect(config('finance.import.max_bytes'))->toBe(2097152)
        ->and(config('finance.import.max_rows'))->toBe(5000)
        ->and(config('finance.transactions.page_size'))->toBe(50)
        ->and(config('finance.recurring.window_days_options'))->toBe([1, 2, 3, 5, 7, 10, 14]);
});

it('suggests an encoding', function () {
    expect(Decoder::suggest("\xEF\xBB\xBFa"))->toBe(['encoding' => 'UTF-8', 'reason' => 'bom'])
        ->and(Decoder::suggest("\xFF\xFEa\0"))->toBe(['encoding' => 'UTF-16LE', 'reason' => 'bom'])
        ->and(Decoder::suggest('Š'))->toBe(['encoding' => 'UTF-8', 'reason' => 'utf8_valid'])
        ->and(Decoder::suggest("a\x8A\x9A\x8E\x9Eb"))->toBe(['encoding' => 'WINDOWS-1250', 'reason' => 'cp1250_bytes'])
        ->and(Decoder::suggest('plain ascii'))->toBe(['encoding' => 'WINDOWS-1250', 'reason' => 'default']);
});

it('decodes Windows-1250 with readable diacritics and rejects mojibake as UTF-8', function () {
    $bytes = CsvFixtures::statement(['encoding' => 'WINDOWS-1250']);
    $file = Decoder::decode($bytes);
    expect($file->text)->toContain('Ľudovít Štúr', 'Škôlka', 'Zaplatené')
        ->and($file->encoding)->toBe('WINDOWS-1250')
        ->and($file->suggested)->toBe('WINDOWS-1250')
        ->and($file->text)->not->toContain("\r");
    expect(refused(fn () => Decoder::decode($bytes, 'UTF-8')))->toBe('decode_failed');
});

it('decodes ISO-8859-2, CP852, UTF-8 BOM and UTF-16', function () {
    $iso = Decoder::decode(CsvFixtures::statement(['encoding' => 'ISO-8859-2']), 'ISO-8859-2');
    expect($iso->text)->toContain('Żabka Łódź')->and($iso->encoding)->toBe('ISO-8859-2');
    expect(Decoder::decode(CsvFixtures::statement(['encoding' => 'CP852']), 'CP852')->text)->toContain('Żabka Łódź', 'Škôlka');
    $bom = Decoder::decode(CsvFixtures::statement(['encoding' => 'UTF-8-BOM']));
    expect($bom->text)->toContain('Ľudovít Štúr')->and($bom->text[0])->not->toBe("\u{FEFF}")->and(str_starts_with($bom->text, "\u{FEFF}"))->toBeFalse()
        ->and($bom->encoding)->toBe('UTF-8');
    expect(Decoder::decode(CsvFixtures::statement(['encoding' => 'UTF-16LE-BOM']))->text)->toContain('Škôlka');
});

it('normalizes newlines and strips controls', function () {
    foreach (['CRLF', 'LF', 'CR'] as $nl) {
        $t = Decoder::decode(CsvFixtures::statement(['newline' => $nl, 'encoding' => 'UTF-8']))->text;
        expect($t)->not->toContain("\r")->and(substr_count($t, "\n"))->toBeGreaterThan(3);
    }
    expect(Decoder::decode("a\x01b\tc\x1Fd\ne", 'UTF-8')->text)->toBe("ab\tcd\ne");
});

it('refuses bad input before parsing', function () {
    expect(refused(fn () => Decoder::decode("PK\x03\x04rest")))->toBe('binary')
        ->and(refused(fn () => Decoder::decode("abc\0def", 'WINDOWS-1250')))->toBe('binary')
        ->and(refused(fn () => Decoder::decode(str_repeat('a', 2097153))))->toBe('too_large')
        ->and(refused(fn () => Decoder::decode('')))->toBe('empty')
        ->and(refused(fn () => Decoder::decode(" \n\t ")))->toBe('empty')
        ->and(refused(fn () => Decoder::decode('abc', 'KOI8-R')))->toBe('decode_failed');
});

it('decodes a diacritics sample in every allowlisted encoding with the iconv of the app image (WR-13)', function () {
    // The suite runs in the app container, so this exercises the production iconv (GNU libiconv), not a host glibc.
    $sample = "Dátum;Popis\n05.01.2026;Zaplatené nájomné Ľudovít Štúr, Łódź, Žilina\n";
    $viaIconv = ['WINDOWS-1250' => 'WINDOWS-1250', 'ISO-8859-2' => 'ISO-8859-2', 'CP852' => 'CP852'];
    foreach ($viaIconv as $encoding) {
        $bytes = iconv('UTF-8', $encoding.'//TRANSLIT', $sample);
        expect($bytes)->not->toBeFalse();
        expect(Decoder::decode($bytes, $encoding)->text)->toContain('Zaplatené nájomné');
    }
    expect(Decoder::decode($sample, 'UTF-8')->text)->toContain('Zaplatené nájomné')
        ->and(Decoder::decode(mb_convert_encoding($sample, 'UTF-16LE', 'UTF-8'), 'UTF-16LE')->text)->toContain('Zaplatené nájomné')
        ->and(Decoder::decode(mb_convert_encoding($sample, 'UTF-16BE', 'UTF-8'), 'UTF-16BE')->text)->toContain('Zaplatené nájomné');

    // Nothing in the allowlist may be untested here.
    expect(array_diff(config('finance.import.encodings'), ['UTF-8', 'UTF-16LE', 'UTF-16BE', ...array_values($viaIconv)]))->toBe([]);
});

it('removes a BOM character without eating the lead byte of a character that shares it (IN-01)', function () {
    expect(Decoder::decode("\u{FF21};b\n1;2\n", 'UTF-8')->text)->toStartWith("\u{FF21};b")
        ->and(Decoder::decode("\xEF\xBB\xBF\u{FF21};b\n1;2\n", 'UTF-8')->text)->toStartWith("\u{FF21};b")
        ->and(Decoder::decode(mb_convert_encoding("\u{FEFF}a;b\n1;2\n", 'UTF-16LE', 'UTF-8'), 'UTF-16LE')->text)->toStartWith('a;b');
});
